import { TestValidator } from "@nestia/e2e";
import typia from "typia";

import api from "../../api";
import { IBbsArticleRoute } from "../../oracle/route/structures/IBbsArticleRoute";

/**
 * Verifies Observable<T> controller returns generate SDK output as T.
 *
 * Locks the native return-type unwrap branch shared by Swagger metadata and
 * generated SDK aliases. NestJS treats Observable<T> as an asynchronous route
 * response just like Promise<T>; a regression would emit Promise<void> or an
 * Observable-shaped schema instead of the resolved article type.
 *
 * 1. Call a controller method that returns Observable<IBbsArticleRoute>.
 * 2. Assign the generated SDK result to IBbsArticleRoute.
 * 3. Assert the runtime payload satisfies the article structure.
 *
 * @evidence contracts/testing.md#behavioral-verification Generated observable result must compile as IBbsArticleRoute, satisfy its exact shape and equal all five handwritten createArticle fields.
 * @evidence contracts/testing.md#independent-expectations Authored Observable<IBbsArticleRoute> and its literal createArticle values establish expected resolved payload independently of generated SDK output. Exact object equality supplements shape validation.
 * @evidence contracts/testing.md#distinguishing-cases Observable return contrasts Promise and direct cached response, with literal fields detecting empty/incorrect resolved output. This does not cover multi-emission or observable errors.
 * @evidence contracts/testing.md#execution-ownership The matching exported function is discovered and awaited by the actual feature executor after generation and compilation. Assertion failures reject its report and empty discovery rejects the entry.
 * @evidence contracts/e2e.md#necessary-boundary Native Observable unwrapping, generated consumer signature and actual Nest resolution/HTTP serialization must connect; a type-unwrapping unit alone cannot prove the received payload.
 * @evidence contracts/e2e.md#shared-execution The request reuses the common packed installation, single producer and generated consumer programs, and one backend; it introduces no independent compilation or server.
 * @evidence contracts/e2e.md#state-isolation-and-reuse-validity Explicit scenario route/type namespaces prevent cross-scenario dispatch; authored request values remain local and the common entry closes the application after all cases settle.
 * @evidence contracts/e2e.md#preserved-coverage The original authored request and exact echo/type/status assertions remain in this case. Generated automated duplicates are regenerated by the common E2eGenerator rather than copied as authored cases.
 */
export const test_route_api_route_observable = async (
  connection: api.IConnection,
): Promise<void> => {
  const article: IBbsArticleRoute =
    await api.functional.route.route.observable(connection);

  typia.assertEquals(article);
  TestValidator.equals<unknown>("resolved article", article, {
    id: "00000000-0000-4000-8000-000000000000",
    title: "Observable route article",
    body: "Observable routes should expose their payload type to generated SDKs.",
    files: [],
    created_at: "2026-06-11T00:00:00.000Z",
  });
};
