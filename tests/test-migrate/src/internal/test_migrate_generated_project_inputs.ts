import assert from "assert/strict";
import fs from "fs";
import path from "path";

import { compileMigrationPrograms } from "./compileMigrationPrograms";

/**
 * Verifies combined migration preparation rejects broken original inputs.
 *
 * Compiling rewritten copies used to bypass generated package exports and
 * project settings. These failures must remain observable before any shared
 * producer runs; the unchanged variants supply the positive control afterward.
 *
 * 1. Redirect the generated SDK export to a missing source and require failure.
 * 2. Supply missing config inheritance and an excluded source root separately.
 * 3. Release each unique negative input before shared original compilation.
 *
 * @evidence contracts/testing.md#behavioral-verification The actual combined preparation must reject missing original exports, nonexistent extends and a rootDir excluding selected files. Each mutation uses its own copied input identity and removes it in finally; integration then compiles unchanged originals.
 * @evidence contracts/testing.md#independent-expectations Node package resolution cannot load a missing export target, and TypeScript rejects missing config bases or sources outside rootDir. Literal missing paths and original source selection establish these expectations independently of emission.
 * @evidence contracts/testing.md#distinguishing-cases Three one-axis malformed inputs distinguish bypassed exports, bypassed inheritance and an ignored rootDir. The existing five-variant combined compile and simulator requests are the normal controls.
 * @evidence contracts/testing.md#execution-ownership The migration integration entry invokes this matching export on its generated positional SDK before compiling all variants. This case owns malformed preparation controls, while direct migration rules remain in the separate unit entry.
 * @evidence contracts/e2e.md#necessary-boundary Generated package identity and actual compiler configuration must reach the shared preparation; source-string checks cannot detect a resolver bypass.
 * @evidence contracts/e2e.md#shared-execution All mutations reuse one already-generated SDK tree. Missing exports fail during Node resolution and malformed config controls use TypeScript configuration parsing only; no extra native compile, consumer installation or backend is prepared.
 * @evidence contracts/e2e.md#state-isolation-and-reuse-validity Unique copied trees isolate each one-axis mutation and Node package-resolution caches; original generated bytes stay unchanged. Finally removes each owned negative input; helper output directories cannot reuse an earlier preparation.
 * @evidence contracts/e2e.md#preserved-coverage Original project/export failure sensitivity is retained while the valid twelve project analyses become one native producer request; unchanged generated modules are consumed afterward.
 */
export const test_migrate_generated_project_inputs = async (
  directory: string,
  cacheDir: string,
): Promise<void> => {
  const owner = path.dirname(directory);
  const mutate = async (
    change: (copy: string) => void,
    check: (operation: () => Promise<string>) => Promise<void>,
  ): Promise<void> => {
    const copy = fs.mkdtempSync(path.join(owner, "invalid-input-"));
    try {
      fs.cpSync(directory, copy, { recursive: true });
      change(copy);
      await check(() => compileMigrationPrograms([copy], cacheDir));
    } finally {
      assert.equal(path.dirname(copy), owner);
      assert.ok(path.basename(copy).startsWith("invalid-input-"));
      fs.rmSync(copy, { recursive: true, force: true });
    }
  };
  await mutate(
    (copy) => {
      const file = path.join(copy, "package.json");
      const manifest = JSON.parse(fs.readFileSync(file, "utf8"));
      manifest.exports["."] = "./src/MissingEntry.ts";
      fs.writeFileSync(file, JSON.stringify(manifest));
    },
    (operation) =>
      assert.rejects(operation, (error: any) => {
        assert.ok(String(error.stderr).includes("MODULE_NOT_FOUND"));
        assert.ok(String(error.stderr).includes("MissingEntry.ts"));
        return true;
      }),
  );
  await mutate(
    (copy) =>
      fs.writeFileSync(
        path.join(copy, "tsconfig.json"),
        JSON.stringify({
          extends: "./missing-base.json",
          include: ["src"],
        }),
      ),
    (operation) =>
      assert.rejects(operation, (error: any) => {
        assert.ok(String(error.message).includes("missing-base.json"));
        return true;
      }),
  );
  await mutate(
    (copy) =>
      fs.writeFileSync(
        path.join(copy, "tsconfig.json"),
        JSON.stringify({
          compilerOptions: { rootDir: "missing-root" },
          include: ["src"],
        }),
      ),
    (operation) => assert.rejects(operation, /root excludes its source/),
  );
};
